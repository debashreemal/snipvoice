// Helper to generate captions state for any array of clips
export function generateCaptionsStateForClips(clips, isReady = false) {
  const state = {};
  clips.forEach((clip) => {
    PLATFORMS.forEach((plat) => {
      const key = `${clip.id}_${plat.id}`;
      const baseHook = clip.hookLine;
      const generic = `Check out this amazing insight from our latest episode! 🔥 ${baseHook}\n\nUnlock your true potential today. 👇\n#CreatorEconomy #Hustle #Bharat`;
      const learned = `${baseHook} Stop wasting time with generic intros. Get straight to the problem statement.`;

      state[key] = {
        text: isReady ? learned : generic,
        original: generic,
        voiceMatch: isReady ? 92 : 58,
        isEdited: isReady,
        regeneratedAfterEdit: false
      };
    });
  });
  return state;
}

