export function generateAutoPlanSlots(approvedClips, projectId = 'proj-1', projectName = '', hasAppliedInsights = false) {
  if (!approvedClips || approvedClips.length === 0) return [];

  // When insights have been applied, prioritize Question hooks
  const sortedClips = [...approvedClips].sort((a, b) => {
    if (hasAppliedInsights) {
      const aIsQuestion = a.hookLine.includes('?') || /^(why|how|what|can|are|is)\b/i.test(a.hookLine);
      const bIsQuestion = b.hookLine.includes('?') || /^(why|how|what|can|are|is)\b/i.test(b.hookLine);
      if (aIsQuestion && !bIsQuestion) return -1;
      if (!aIsQuestion && bIsQuestion) return 1;
    }
    return b.score - a.score;
  });

  const slots = [];
  // Prioritize evening slots (Instagram 7 PM, YouTube Shorts 6 PM) when insights are applied
  const platforms = hasAppliedInsights
    ? ['instagram', 'youtube', 'linkedin', 'x']
    : ['linkedin', 'instagram', 'x', 'youtube'];
  const dayKeys = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'];

  const dayTracker = {};
  dayKeys.forEach((d) => {
    dayTracker[d] = { count: 0, platforms: new Set() };
  });

  let clipIndex = 0;
  let platformIndex = 0;
  const targetCount = Math.min(sortedClips.length * 2, 7);

  for (let i = 0; i < targetCount; i++) {
    const clip = sortedClips[clipIndex % sortedClips.length];
    const platformKey = platforms[platformIndex % platforms.length];
    const config = PLATFORM_SCHEDULE_CONFIG[platformKey];

    let chosenDayKey = null;
    for (const d of dayKeys) {
      if (dayTracker[d].count < 2 && !dayTracker[d].platforms.has(platformKey)) {
        chosenDayKey = d;
        break;
      }
    }

    if (chosenDayKey) {
      dayTracker[chosenDayKey].count += 1;
      dayTracker[chosenDayKey].platforms.add(platformKey);

      const dayObj = WEEK_DAYS.find((w) => w.key === chosenDayKey);

      slots.push({
        id: `slot-${Date.now()}-${i}-${Math.random()}`,
        projectId,
        projectName: projectName || 'Project',
        clipId: clip.id,
        hookLine: clip.hookLine,
        platform: platformKey,
        platformName: config.name,
        time: config.defaultTime,
        day: chosenDayKey,
        date: dayObj ? dayObj.date : '',
        dayNumber: dayObj ? dayObj.dayNumber : 23,
        reason: hasAppliedInsights
          ? 'Planned using your last results: scheduled during peak evening retention.'
          : config.reason,
        isPosted: false,
        plannedWithInsights: hasAppliedInsights
      });
    }

    clipIndex++;
    platformIndex++;
  }

  return slots;
}

